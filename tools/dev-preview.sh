#!/usr/bin/env bash
#
# Local preview harness — a development helper, NOT part of the theme or the
# plugin that ship to the customer.
#
# Builds a throw-away WordPress installation in $HOME/.wptest with SQLite (no
# MySQL needed), installs the theme and the plugin from this repository and
# imports the demo content, so the site can be previewed on port 9400.
#
#     tools/dev-preview.sh            # build / repair the installation
#     bash ~/.wptest/serve.sh         # start the preview server (port 9400)
#
# Run this script while the preview server is stopped: both write to the same
# SQLite file, and an instance that is still running can write a stale copy of
# the options back over the freshly imported ones.
#
# Requirements: node 18+, npm, curl, tar. Only the WordPress GitHub mirrors and
# the npm registry are used.
#
set -euo pipefail

HARNESS="${WP_HARNESS_DIR:-$HOME/.wptest}"
WP="$HARNESS/wp"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
WP_VERSION="${WP_VERSION:-7.1.3}"
SQLITE_REF="refs/heads/main"
PORT="${WP_PORT:-9400}"

log() { printf '\033[1;32m›\033[0m %s\n' "$*"; }

mkdir -p "$HARNESS"

# ---------------------------------------------------------------------------
# 1. Node dependencies (WordPress Playground CLI runs PHP + the web server)
# ---------------------------------------------------------------------------
if [ ! -f "$HARNESS/node_modules/@wp-playground/cli/cli.js" ]; then
	log "installing @wp-playground/cli (first run only)"

	cat > "$HARNESS/package.json" <<'JSON'
{
  "name": "wptest-harness",
  "private": true,
  "version": "1.0.0",
  "description": "Local preview harness for the ZabiSoft theme and plugin"
}
JSON

	( cd "$HARNESS" && npm install --no-audit --no-fund @wp-playground/cli php-parser >/dev/null )
fi

CLI="$HARNESS/node_modules/@wp-playground/cli/cli.js"

# ---------------------------------------------------------------------------
# 2. WordPress core
# ---------------------------------------------------------------------------
if [ ! -f "$WP/wp-includes/version.php" ]; then
	log "downloading WordPress $WP_VERSION"

	[ -f "$HARNESS/wp-$WP_VERSION.tar.gz" ] || \
		curl -sL "https://codeload.github.com/WordPress/WordPress/tar.gz/refs/tags/$WP_VERSION" -o "$HARNESS/wp-$WP_VERSION.tar.gz"

	mkdir -p "$WP"
	tar xzf "$HARNESS/wp-$WP_VERSION.tar.gz" -C "$WP" --strip-components=1

	# Only the default theme that the archive ships is needed.
	find "$WP/wp-content/themes" -maxdepth 1 -mindepth 1 -type d \
		! -name 'twentytwentyfive' -exec rm -rf {} +
fi

# ---------------------------------------------------------------------------
# 3. SQLite database integration
# ---------------------------------------------------------------------------
SQLITE_PLUGIN="$WP/wp-content/plugins/sqlite-database-integration"

if [ ! -d "$SQLITE_PLUGIN" ]; then
	log "downloading the SQLite database integration"

	[ -f "$HARNESS/sqlite-database-integration.tar.gz" ] || \
		curl -sL "https://codeload.github.com/WordPress/sqlite-database-integration/tar.gz/$SQLITE_REF" \
			-o "$HARNESS/sqlite-database-integration.tar.gz"

	tar xzf "$HARNESS/sqlite-database-integration.tar.gz" -C "$HARNESS"

	mv "$HARNESS"/sqlite-database-integration-* "$SQLITE_PLUGIN"
fi

# ---------------------------------------------------------------------------
# 4. wp-config.php, the SQLite drop-in and the dynamic-URL mu-plugin
# ---------------------------------------------------------------------------
if [ ! -f "$WP/wp-config.php" ]; then
	log "writing wp-config.php and the SQLite drop-in"

	python3 - "$WP" <<'PY'
import pathlib, secrets, sys

root = pathlib.Path(sys.argv[1])
plugin = root / 'wp-content/plugins/sqlite-database-integration'

drop_in = (plugin / 'db.copy').read_text()
drop_in = drop_in.replace('{SQLITE_IMPLEMENTATION_FOLDER_PATH}', '/wordpress/wp-content/plugins/sqlite-database-integration')
drop_in = drop_in.replace('{SQLITE_PLUGIN}', 'sqlite-database-integration/load.php')
(root / 'wp-content/db.php').write_text(drop_in)

salts = "\n".join(
    "define( '%s', '%s' );" % (key, secrets.token_urlsafe(48).replace("'", '').replace('"', ''))
    for key in ('AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY',
                'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT')
)

(root / 'wp-config.php').write_text("""<?php
/**
 * Preview installation of the ZabiSoft site (SQLite, no MySQL needed).
 * Generated by tools/dev-preview.sh – never part of the delivered package.
 */

define( 'DB_NAME', 'wordpress' );
define( 'DB_USER', 'wordpress' );
define( 'DB_PASSWORD', 'wordpress' );
define( 'DB_HOST', 'localhost' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );

// SQLite integration --------------------------------------------------------
define( 'DB_DIR', __DIR__ . '/wp-content/database/' );
define( 'DB_FILE', 'demo.sqlite' );

%s

$table_prefix = 'wp_';

define( 'WP_DEBUG', true );
define( 'WP_DEBUG_LOG', true );
define( 'WP_DEBUG_DISPLAY', false );
define( 'DISALLOW_FILE_EDIT', true );
define( 'WP_ENVIRONMENT_TYPE', 'local' );

if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', __DIR__ . '/' );
}

require_once ABSPATH . 'wp-settings.php';
""" % salts)

(root / 'wp-content/database').mkdir(exist_ok=True)
(root / 'wp-content/mu-plugins').mkdir(exist_ok=True)
PY

	cat > "$WP/wp-content/mu-plugins/zz-dynamic-url.php" <<'PHP'
<?php
/**
 * Keeps the preview site URL in sync with whatever host the request arrives on,
 * so one SQLite database works for the CLI, for localhost:9400 and for the
 * Arena preview proxy.
 */

$zsm_host = $_SERVER['HTTP_HOST'] ?? '';

if ( $zsm_host ) {
	$zsm_scheme = 'http';

	if ( ( $_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '' ) === 'https' || ( $_SERVER['HTTPS'] ?? '' ) === 'on' ) {
		$zsm_scheme = 'https';
	}

	$zsm_url = $zsm_scheme . '://' . $zsm_host;

	add_filter( 'pre_option_home', static fn() => $zsm_url );
	add_filter( 'pre_option_siteurl', static fn() => $zsm_url );
}
PHP
fi

# ---------------------------------------------------------------------------
# 5. The scripts the harness runs through the Playground PHP binary
# ---------------------------------------------------------------------------
cat > "$HARNESS/install.php" <<'PHP'
<?php
/** Installs WordPress into the SQLite database. */

define( 'WP_INSTALLING', true );
define( 'WP_USE_THEMES', false );

require '/wordpress/wp-load.php';
require_once ABSPATH . 'wp-admin/includes/upgrade.php';

if ( is_blog_installed() ) {
	echo "already installed\n";
} else {
	$result = wp_install( 'ZabiSoft', 'admin', 'admin@example.com', true, '', 'adminpass' );

	echo is_wp_error( $result )
		? 'install error: ' . $result->get_error_message() . "\n"
		: "installed: user {$result['user_id']}\n";
}

echo 'WordPress ' . get_bloginfo( 'version' ) . "\n";
PHP

cat > "$HARNESS/setup.php" <<'PHP'
<?php
/** Activates the theme and the plugin, sets the options and imports the demo. */

define( 'WP_USE_THEMES', false );

require '/wordpress/wp-load.php';
require_once ABSPATH . 'wp-admin/includes/plugin.php';
require_once ABSPATH . 'wp-admin/includes/theme.php';

if ( ! wp_get_theme( 'zabisoft' )->exists() ) {
	echo "THEME MISSING\n";
	exit( 1 );
}

switch_theme( 'zabisoft' );
echo 'theme: ' . get_option( 'stylesheet' ) . "\n";

$plugin = 'zabisoft-software-manager/zabisoft-software-manager.php';

if ( ! is_plugin_active( $plugin ) ) {
	$result = activate_plugin( $plugin );

	if ( is_wp_error( $result ) ) {
		echo 'plugin error: ' . $result->get_error_message() . "\n";
	}
}

echo 'plugin: ' . ( is_plugin_active( $plugin ) ? 'active' : 'inactive' ) . "\n";

update_option( 'permalink_structure', '/%postname%/' );
update_option( 'blogname', 'ZabiSoft' );
update_option( 'blogdescription', 'Download Free Your Desired Software' );
update_option( 'show_on_front', 'posts' );
update_option( 'posts_per_page', 10 );
update_option( 'blog_public', 1 );

if ( ! class_exists( 'ZSM_Demo_Content' ) ) {
	echo "plugin classes missing\n";
	exit( 1 );
}

$demo = new ZSM_Demo_Content();
$demo->remove();
$demo->import();

// The theme's widget classes are only registered once WordPress has loaded the
// active theme, which is exactly what happened above.
$demo->maybe_seed_pending_widgets();

// Menus: the importer assigns the theme locations, but a fresh installation may
// still be holding the previous theme's mods, so set them explicitly.
$locations = array();

foreach ( wp_get_nav_menus() as $menu ) {
	if ( 'Main menu' === $menu->name ) {
		$locations['primary'] = (int) $menu->term_id;
		$locations['topbar']  = (int) $menu->term_id;
	}

	if ( 'Footer menu' === $menu->name ) {
		$locations['footer'] = (int) $menu->term_id;
	}
}

set_theme_mod( 'nav_menu_locations', $locations );

delete_option( 'rewrite_rules' );
flush_rewrite_rules( true );

$sidebars = get_option( 'sidebars_widgets', array() );

echo 'software entries: ' . wp_count_posts( 'software' )->publish . "\n";
echo 'pages: ' . wp_count_posts( 'page' )->publish . "\n";
echo 'categories: ' . wp_count_terms( array( 'taxonomy' => 'software_category', 'hide_empty' => false ) ) . "\n";
echo 'menu locations: ' . wp_json_encode( get_nav_menu_locations() ) . "\n";
echo 'sidebar-1 widgets: ' . wp_json_encode( $sidebars['sidebar-1'] ?? array() ) . "\n";
echo "ready\n";
PHP

# ---------------------------------------------------------------------------
# 6. A PHP syntax linter (php-parser), so checked-in code can be verified
# ---------------------------------------------------------------------------
cat > "$HARNESS/lint.mjs" <<'JS'
// PHP syntax check with php-parser: node lint.mjs <dir-or-file>
import { readdirSync, statSync, readFileSync } from 'node:fs';
import { join, extname } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire( import.meta.url );
const parser = require( 'php-parser' );
const engine = new parser.Engine( { parser: { extractDoc: true, suppressErrors: false }, ast: { withPositions: true } } );

const files = [];

function walk( path ) {
	if ( statSync( path ).isDirectory() ) {
		for ( const entry of readdirSync( path ) ) {
			walk( join( path, entry ) );
		}
	} else if ( extname( path ) === '.php' ) {
		files.push( path );
	}
}

for ( const target of process.argv.slice( 2 ) ) {
	walk( target );
}

let bad = 0;

for ( const file of files ) {
	try {
		engine.parseCode( readFileSync( file, 'utf8' ), file );
	} catch ( error ) {
		bad++;
		console.log( 'FAIL ' + file + ' line ' + ( error.lineNumber || '?' ) + ': ' + ( error.message || error ) );
	}
}

console.log( `php-parser checked ${ files.length } files, ${ bad } with problems.` );
process.exit( bad ? 1 : 0 );
JS

# ---------------------------------------------------------------------------
# 7. Run both scripts inside WordPress, with the repository mounted live
# ---------------------------------------------------------------------------
run_php() {
	node "$CLI" php \
		--wordpress-install-mode=do-not-attempt-installing \
		--mount-before-install="$WP:/wordpress" \
		--mount="$HARNESS:/wptest" \
		--mount="$REPO/src/themes/zabisoft:/wordpress/wp-content/themes/zabisoft" \
		--mount="$REPO/src/plugins/zabisoft-software-manager:/wordpress/wp-content/plugins/zabisoft-software-manager" \
		-- "/wptest/$1" 2>&1 | grep -vE 'worker count|only 2 CPU|deadlock'
}

log "installing WordPress and the demo content"
run_php install.php
run_php setup.php

# Second pass: in the request that activates the theme, the theme's own widget
# classes are not registered yet, so the placement of the sidebar widgets is
# retried once the theme is loaded for real.
run_php setup.php

# ---------------------------------------------------------------------------
# 8. The server script
# ---------------------------------------------------------------------------
cat > "$HARNESS/serve.sh" <<EOF
#!/bin/bash
# Preview server: WordPress $WP_VERSION with the theme and the plugin mounted
# live from $REPO.
cd "$HARNESS"
exec node "$CLI" server \\
  --port=$PORT \\
  --wordpress-install-mode=do-not-attempt-installing \\
  --mount-before-install=$WP:/wordpress \\
  --mount=$REPO/src/themes/zabisoft:/wordpress/wp-content/themes/zabisoft \\
  --mount=$REPO/src/plugins/zabisoft-software-manager:/wordpress/wp-content/plugins/zabisoft-software-manager
EOF

chmod +x "$HARNESS/serve.sh"

log "done — start the preview with: bash $HARNESS/serve.sh  (port $PORT)"
