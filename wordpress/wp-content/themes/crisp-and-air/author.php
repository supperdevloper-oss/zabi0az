<?php
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}
get_header();
$author_id = (int) get_queried_object_id();
$author    = get_user_by( 'id', $author_id );
$bio       = ca_recipe_author_bio( $author_id );
$photo     = ca_recipe_author_photo( $author_id, 'ca-author' );
?>
<main id="main-content" class="site-main author-page">
	<section class="author-hero">
		<div class="wrap author-hero__inner">
			<?php ca_theme_breadcrumbs(); ?>
			<div class="author-hero__profile">
				<div class="author-hero__avatar"><?php if ( $photo ) : ?><?php echo $photo; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Image HTML generated by WordPress. ?><?php else : ?><span aria-hidden="true"><?php echo esc_html( strtoupper( substr( $author ? $author->display_name : 'C', 0, 1 ) ) ); ?></span><?php endif; ?></div>
				<div><p class="section-heading__kicker"><?php esc_html_e( 'Meet the author', 'crisp-and-air' ); ?></p><h1><?php echo esc_html( $author ? $author->display_name : __( 'Recipe author', 'crisp-and-air' ) ); ?></h1><?php if ( $bio ) : ?><p class="author-hero__bio"><?php echo esc_html( $bio ); ?></p><?php else : ?><p class="author-hero__bio"><?php esc_html_e( 'Recipes published on Crisp & Air. Add a short, accurate author bio in Users → Profile.', 'crisp-and-air' ); ?></p><?php endif; ?></div>
			</div>
		</div>
	</section>
	<div class="wrap archive-content">
		<div class="section-heading"><span class="section-heading__kicker"><?php esc_html_e( 'From this author', 'crisp-and-air' ); ?></span><h2><?php esc_html_e( 'Recipes', 'crisp-and-air' ); ?></h2></div>
		<?php if ( have_posts() ) : ?>
			<div class="recipe-grid recipe-grid--three"><?php while ( have_posts() ) : the_post(); ca_theme_recipe_card( get_the_ID() ); endwhile; ?></div>
			<?php ca_theme_pagination(); ?>
		<?php else : ?><div class="empty-library"><p><?php esc_html_e( 'No published recipes are assigned to this author yet.', 'crisp-and-air' ); ?></p></div><?php endif; ?>
	</div>
</main>
<?php get_footer(); ?>
